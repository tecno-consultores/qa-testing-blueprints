function sanitizeSingleLineSec06(rawText: string): string {
  let clean = rawText
    .normalize('NFKC')
    .replace(ANSI_ESCAPE_RE, '')
    .replace(/[\r\n]+/g, ' ')
    .trim();
  for (const [pattern, replacement] of SECRET_REDACTION_PATTERNS) {
    clean = clean.replace(pattern, replacement);
  }
  return clean;
}

function isContainedPath(rootReal: string, targetReal: string): boolean {
  const rel = path.relative(rootReal, targetReal);
  return rel !== '..' && !rel.startsWith(`..${path.sep}`) && !path.isAbsolute(rel);
}

function resolveContainedWorkspace(projectPathInput?: string): {
  readonly ok: true;
  readonly realRoot: string;
} | {
  readonly ok: false;
  readonly error: string;
} {
  const raw = (projectPathInput ?? process.cwd()).normalize('NFKC').trim();
  if (!raw || raw.includes('\0')) {
    return { ok: false, error: 'Ruta de workspace vacía o con bytes nulos.' };
  }
  const resolved = path.resolve(raw);
  if (!fs.existsSync(resolved) || !fs.statSync(resolved).isDirectory()) {
    return { ok: false, error: `Workspace inexistente o no es directorio: ${resolved}` };
  }
  return { ok: true, realRoot: fs.realpathSync(resolved) };
}

function assertSafeAncestorDirectories(realRoot: string, startDir: string): void {
  let cursor = startDir;
  while (cursor !== realRoot && isContainedPath(realRoot, cursor)) {
    if (fs.existsSync(cursor) && fs.lstatSync(cursor).isSymbolicLink()) {
      throw new Error(`Directorio symlink rechazado por seguridad: ${cursor}`);
    }
    cursor = path.dirname(cursor);
  }
}

function assertSafeTargetPath(realRoot: string, relPath: string): string {
  const candidate = path.resolve(realRoot, relPath);
  assertSafeAncestorDirectories(realRoot, path.dirname(candidate));
  if (fs.existsSync(candidate) && fs.lstatSync(candidate).isSymbolicLink()) {
    throw new Error(`Symlink rechazado por seguridad en archivo de estado: ${relPath}`);
  }
  return candidate;
}

function atomicWriteWithMode(filePath: string, content: string, mode: number, dirMode = 0o700): void {
  const dir = path.dirname(filePath);
  fs.mkdirSync(dir, { recursive: true, mode: dirMode });
  if (dir.endsWith(`${path.sep}.cache`)) {
    fs.chmodSync(dir, 0o700);
  }
  const tmpPath = path.join(dir, `.${path.basename(filePath)}.${process.pid}.tmp`);
  fs.writeFileSync(tmpPath, content, { encoding: UTF8_ENCODING, mode });
  fs.chmodSync(tmpPath, mode);
  fs.renameSync(tmpPath, filePath);
}

function runGitCapture(
  realRoot: string,
  gitArgs: readonly string[],
  execFileSyncFn: typeof execFileSync
): string | null {
  try {
    const out = execFileSyncFn('git', gitArgs, {
      cwd: realRoot,
      encoding: UTF8_ENCODING,
      timeout: 5000,
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    return String(out).trimEnd();
  } catch (err: unknown) {
    // Non-git workspace or git binary absent falls back to git_available=false snapshot
    reportDebugCatchError(`sessionFlightRecorder.runGitCapture(${pickAt(gitArgs, 0, 'git')})`, err);
    return null;
  }
}

function isCacheOrProjectedPath(relPath: string): boolean {
  const norm = relPath.replace(/\\/g, '/').replace(/^"|"$/g, '');
  return (
    norm === '.agents/ACTIVE_TASK.md' ||
    norm === '.agents/.cache' ||
    norm.startsWith('.agents/.cache/')
  );
}

function collectLiveGitSnapshot(realRoot: string, execFileSyncFn: typeof execFileSync): {
  readonly git_available: boolean;
  readonly branch: string;
  readonly head_sha: string;
  readonly dirty_files_excluding_cache: string[];
  readonly diff_stat: string;
} {
  const branchRaw =
    runGitCapture(realRoot, ['rev-parse', '--abbrev-ref', 'HEAD'], execFileSyncFn) ??
    runGitCapture(realRoot, ['symbolic-ref', '--short', 'HEAD'], execFileSyncFn);
  if (branchRaw === null) {
    return {
      git_available: false,
      branch: 'nogit',
      head_sha: 'none',
      dirty_files_excluding_cache: [],
      diff_stat: '',
    };
  }
  const headSha = runGitCapture(realRoot, ['rev-parse', '--short', 'HEAD'], execFileSyncFn) ?? 'unborn';
  const statusRaw = runGitCapture(realRoot, ['status', '--porcelain'], execFileSyncFn) ?? '';
  const dirtyFiles: string[] = [];
  for (const line of statusRaw.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const rawEntry = line.slice(3).trim();
    const arrowIdx = rawEntry.indexOf(' -> ');
    const targetPath = arrowIdx === -1 ? rawEntry : rawEntry.slice(arrowIdx + 4);
    if (!isCacheOrProjectedPath(targetPath)) {
      dirtyFiles.push(targetPath);
    }
  }
  const diffStat = runGitCapture(realRoot, ['diff', '--stat'], execFileSyncFn) ?? '';
  return {
    git_available: true,
    branch: branchRaw.trim(),
    head_sha: headSha.trim(),
    dirty_files_excluding_cache: dirtyFiles,
    diff_stat: diffStat.trim(),
  };
}

function normalizeStringList(items: readonly string[]): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const raw of items) {
    const clean = sanitizeSingleLineSec06(String(raw));
    if (clean && !seen.has(clean)) {
      seen.add(clean);
      out.push(clean);
    }
  }
  return out;
}

function parseGlobLine(line: string, prefix: 'allowed_globs' | 'forbidden_globs'): string[] {
  const trimmed = line.trim();
  const keyPrefix = `${prefix}:`;
  if (!trimmed.startsWith(keyPrefix)) return [];
  const rest = trimmed.slice(keyPrefix.length).trim();
  return rest
    .slice(1, -1)
    .split(',')
    .map((part) => part.trim().replace(/^['"`]|['"`]$/g, ''))
    .filter(Boolean);
}

function hydrateFromExistingActiveTask(
  activeTaskPath: string,
  gitInfo: { readonly git_available: boolean; readonly branch: string; readonly head_sha: string }
): SessionCheckpointDocument | null {
  if (!fs.existsSync(activeTaskPath)) return null;
  const lines = fs.readFileSync(activeTaskPath, UTF8_ENCODING).split(/\r?\n/);
  const completed: string[] = [];
  const pending: string[] = [];
  const allowedGlobs: string[] = [];
  const forbiddenGlobs: string[] = [];
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('- [x] ')) {
      completed.push(sanitizeSingleLineSec06(trimmed.slice(6)));
    } else if (trimmed.startsWith('- [ ] ')) {
      pending.push(sanitizeSingleLineSec06(trimmed.slice(6)));
    } else if (trimmed.startsWith('allowed_globs:')) {
      allowedGlobs.push(...parseGlobLine(trimmed, 'allowed_globs'));
    } else if (trimmed.startsWith('forbidden_globs:')) {
      forbiddenGlobs.push(...parseGlobLine(trimmed, 'forbidden_globs'));
    }
  }
  const activeStep = pending[0] ?? 'RECOVERED';
  return {
    schema_version: '1.0',
    status: 'IN_PROGRESS',
    updated_at: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'),
    git_available: gitInfo.git_available,
    branch: gitInfo.branch,
    base_sha: gitInfo.head_sha,
    task_id: 'HYDRATED',
    completed_steps: completed,
    active_step: activeStep,
    planned_steps: normalizeStringList([activeStep, ...pending]),
    allowed_globs: normalizeStringList(allowedGlobs),
    forbidden_globs: normalizeStringList(forbiddenGlobs),
    intent_140chars: 'Estado hidratado automáticamente desde ACTIVE_TASK.md previo',
  };
}

function readExistingCheckpoint(
  checkpointPath: string,
  activeTaskPath: string,
  gitInfo: { readonly git_available: boolean; readonly branch: string; readonly head_sha: string }
): SessionCheckpointDocument | null {
  if (fs.existsSync(checkpointPath)) {
    return JSON.parse(fs.readFileSync(checkpointPath, UTF8_ENCODING)) as SessionCheckpointDocument;
  }
  return hydrateFromExistingActiveTask(activeTaskPath, gitInfo);
}

function renderActiveTaskProjection(doc: SessionCheckpointDocument): string {
  const datePart = doc.updated_at.slice(0, 10);
  const stateLabel = doc.status === 'CERTIFIED_CLEAN' ? 'CERTIFIED_CLEAN' : 'IN_PROGRESS';
  const lines: string[] = [
    '# SPDX-License-Identifier: MIT',
    '# Active Task — Proyección Atómica QA-11X',
    AUTO_GEN_MARKER,
    '',
    `**Fecha:** ${datePart} | **Tarea:** \`${doc.task_id}\` | **Rama:** \`${doc.branch}@${doc.base_sha}\` | **Estado:** ${stateLabel}`,
    `**Objetivo Activo (\`${doc.active_step}\`):** ${doc.intent_140chars}`,
  ];
  if (doc.allowed_globs.length > 0) {
    lines.push(`allowed_globs: [${doc.allowed_globs.join(', ')}]`);
  }
  if (doc.forbidden_globs.length > 0) {
    lines.push(`forbidden_globs: [${doc.forbidden_globs.join(', ')}]`);
  }
  if (doc.last_script_run) {
    lines.push(
      `**Último Comando:** \`${doc.last_script_run.cmd}\` (exit=${doc.last_script_run.exit_code}) — ${doc.last_script_run.summary_1line}`
    );
  }
  lines.push('', '## 📋 Progreso Atómico');

  const doneSet = new Set(doc.completed_steps);
  const checkboxLines: string[] = [];
  for (const step of doc.completed_steps) {
    checkboxLines.push(`- [x] ${step}`);
  }
  const remainingSource = [doc.active_step, ...doc.planned_steps].filter(Boolean);
  const seenRemaining = new Set<string>();
  for (const step of remainingSource) {
    if (doneSet.has(step) || seenRemaining.has(step)) continue;
    seenRemaining.add(step);
    checkboxLines.push(doc.status === 'CERTIFIED_CLEAN' ? `- [x] ${step}` : `- [ ] ${step}`);
  }

  const maxCheckboxes = Math.max(1, MAX_ACTIVE_TASK_LINES - lines.length);
  if (checkboxLines.length > maxCheckboxes) {
    const headCount = Math.max(1, maxCheckboxes - 1);
    const omitted = checkboxLines.length - headCount;
    lines.push(...checkboxLines.slice(0, headCount), `- [x] ... (+${omitted} pasos compactados)`);
  } else {
    lines.push(...checkboxLines);
  }
  return `${lines.slice(0, MAX_ACTIVE_TASK_LINES).join('\n')}\n`;
}

function buildPythonCliArgs(
  realRoot: string,
  action: FlightRecorderAction,
  args: SessionFlightRecorderArgs
): string[] {
  const scriptPath = path.join(realRoot, CHECKPOINT_CTL_REL_PATH);
  if (action === ACTION_RECOVER) {
    return [scriptPath, ACTION_RECOVER, WORKSPACE_FLAG, realRoot, '--json'];
  }
  if (action === ACTION_CLEAR) {
    return [scriptPath, ACTION_CLEAR, WORKSPACE_FLAG, realRoot];
  }
  const cli = [
    scriptPath,
    'set',
    WORKSPACE_FLAG,
    realRoot,
    '--task-id',
    sanitizeSingleLineSec06(args.task_id ?? ''),
    '--step',
    sanitizeSingleLineSec06(args.active_step ?? ''),
    '--intent',
    sanitizeSingleLineSec06(args.intent_140chars ?? ''),
  ];
  if (args.completed_steps && args.completed_steps.length > 0) {
    cli.push('--done', args.completed_steps.join(','));
  }
  if (args.planned_steps && args.planned_steps.length > 0) {
    cli.push('--planned', args.planned_steps.join(','));
  }
  if (args.allowed_globs && args.allowed_globs.length > 0) {
    cli.push('--allowed-globs', args.allowed_globs.join(','));
  }
  if (args.forbidden_globs && args.forbidden_globs.length > 0) {
    cli.push('--forbidden-globs', args.forbidden_globs.join(','));
  }
  return cli;
}

function execFileAsync(
  executor: typeof execFile,
  file: string,
  cliArgs: readonly string[],
  cwd: string
): Promise<{ readonly exitCode: number; readonly errorCode?: string; readonly stdout: string; readonly stderr: string }> {
  return new Promise((resolve) => {
    executor(
      file,
      cliArgs,
      { cwd, shell: false, timeout: EXEC_TIMEOUT_MS, encoding: UTF8_ENCODING },
      (error, stdout, stderr) => {
        if (!error) {
          resolve({ exitCode: 0, stdout: String(stdout), stderr: String(stderr) });
          return;
        }
        const errInfo = error as NodeJS.ErrnoException & { code?: number | string };
        resolve({
          exitCode: typeof errInfo.code === 'number' ? errInfo.code : 1,
          errorCode: typeof errInfo.code === 'string' ? errInfo.code : undefined,
          stdout: String(stdout),
          stderr: String(stderr),
        });
      }
    );
  });
}

function persistCheckpointAndProjection(
  checkpointPath: string,
  activeTaskPath: string,
  doc: SessionCheckpointDocument
): string {
  atomicWriteWithMode(checkpointPath, `${JSON.stringify(doc, null, 2)}\n`, 0o600);
  const projectedMd = renderActiveTaskProjection(doc);
  atomicWriteWithMode(activeTaskPath, projectedMd, 0o644);
  return projectedMd;
}

function validateSaveInputs(args: SessionFlightRecorderArgs): string | null {
  const taskId = sanitizeSingleLineSec06(args.task_id ?? '');
  const activeStep = sanitizeSingleLineSec06(args.active_step ?? '');
  const intent = sanitizeSingleLineSec06(args.intent_140chars ?? '');
  if (!taskId || !activeStep || !intent) {
    return "Acción 'save' requiere 'task_id', 'active_step' e 'intent_140chars' no vacíos.";
  }
  const intentLength = [...intent].length;
  if (intentLength > MAX_INTENT_CHARS) {
    return `intent_140chars excede el límite estricto de ${MAX_INTENT_CHARS} caracteres (${intentLength}).`;
  }
  return null;
}

interface NativeActionContext {
  readonly realRoot: string;
  readonly checkpointPath: string;
  readonly activeTaskPath: string;
  readonly execFileSyncFn: typeof execFileSync;
}

function executeNativeSave(
  args: SessionFlightRecorderArgs,
  ctx: NativeActionContext
): FlightRecorderResult {
  const gitLive = collectLiveGitSnapshot(ctx.realRoot, ctx.execFileSyncFn);
  const prior = readExistingCheckpoint(ctx.checkpointPath, ctx.activeTaskPath, gitLive);
  const doneSteps = args.completed_steps !== undefined
    ? normalizeStringList(args.completed_steps)
    : prior?.completed_steps ?? [];
  const plannedSteps = args.planned_steps !== undefined
    ? normalizeStringList(args.planned_steps)
    : prior?.planned_steps ?? [];
  const allowedGlobs = args.allowed_globs !== undefined
    ? normalizeStringList(args.allowed_globs)
    : prior?.allowed_globs ?? [];
  const forbiddenGlobs = args.forbidden_globs !== undefined
    ? normalizeStringList(args.forbidden_globs)
    : prior?.forbidden_globs ?? [];
  const activeStep = sanitizeSingleLineSec06(args.active_step as string);
  const cleanIntent = sanitizeSingleLineSec06(args.intent_140chars as string);
  const nextDoc: SessionCheckpointDocument = {
    schema_version: '1.0',
    status: 'IN_PROGRESS',
    updated_at: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'),
    git_available: gitLive.git_available,
    branch: gitLive.branch,
    base_sha: gitLive.head_sha,
    task_id: sanitizeSingleLineSec06(args.task_id as string),
    completed_steps: doneSteps,
    active_step: activeStep,
    planned_steps: plannedSteps,
    allowed_globs: allowedGlobs,
    forbidden_globs: forbiddenGlobs,
    intent_140chars: cleanIntent,
    ...(prior?.last_script_run ? { last_script_run: prior.last_script_run } : {}),
  };
  const projected = persistCheckpointAndProjection(ctx.checkpointPath, ctx.activeTaskPath, nextDoc);
  return {
    status: 'PASSED',
    action: ACTION_SAVE,
    backend: BACKEND_NATIVE_TS,
    summary_1line: `[PASS] CHECKPOINT | Task: ${nextDoc.task_id} | Active: ${activeStep} | Done: ${doneSteps.length}`,
    checkpoint_path: ctx.checkpointPath,
    active_task_path: ctx.activeTaskPath,
    checkpoint: nextDoc,
    git_live: gitLive,
    active_task_markdown: projected,
  };
}

function executeNativeRecover(
  _args: SessionFlightRecorderArgs,
  ctx: NativeActionContext
): FlightRecorderResult {
  const gitLive = collectLiveGitSnapshot(ctx.realRoot, ctx.execFileSyncFn);
  const doc = readExistingCheckpoint(ctx.checkpointPath, ctx.activeTaskPath, gitLive);
  if (!doc) {
    return {
      status: 'FAILED',
      action: ACTION_RECOVER,
      backend: BACKEND_NATIVE_TS,
      summary_1line: `[FAIL] CHECKPOINT | Estado no inicializado en ${ctx.checkpointPath}`,
      checkpoint_path: ctx.checkpointPath,
      active_task_path: ctx.activeTaskPath,
      checkpoint: null,
      git_live: gitLive,
      error: 'No existe session_checkpoint.json ni ACTIVE_TASK.md previo para recuperar.',
    };
  }
  const projected = fs.existsSync(ctx.activeTaskPath)
    ? fs.readFileSync(ctx.activeTaskPath, UTF8_ENCODING)
    : persistCheckpointAndProjection(ctx.checkpointPath, ctx.activeTaskPath, doc);
  return {
    status: 'PASSED',
    action: ACTION_RECOVER,
    backend: BACKEND_NATIVE_TS,
    summary_1line: `[PASS] RECOVER | Task: ${doc.task_id} | Status: ${doc.status} | Dirty: ${gitLive.dirty_files_excluding_cache.length}`,
    checkpoint_path: ctx.checkpointPath,
    active_task_path: ctx.activeTaskPath,
    checkpoint: doc,
    git_live: gitLive,
    active_task_markdown: projected,
  };
}

function executeNativeClear(
  args: SessionFlightRecorderArgs,
  ctx: NativeActionContext
): FlightRecorderResult {
  const gitLive = collectLiveGitSnapshot(ctx.realRoot, ctx.execFileSyncFn);
  const existing = readExistingCheckpoint(ctx.checkpointPath, ctx.activeTaskPath, gitLive);
  if (!existing) {
    return {
      status: 'PASSED',
      action: ACTION_CLEAR,
      backend: BACKEND_NATIVE_TS,
      summary_1line: '[PASS] CLEAR | Sin checkpoint previo; nada que cerrar.',
      checkpoint_path: ctx.checkpointPath,
      active_task_path: ctx.activeTaskPath,
      checkpoint: null,
      git_live: gitLive,
    };
  }
  const reasonSuffix = args.reason?.trim() ? ` | Motivo: ${sanitizeSingleLineSec06(args.reason)}` : '';
  const doneSet = new Set(existing.completed_steps);
  const remaining = [existing.active_step, ...existing.planned_steps].filter(
    (step) => step && !doneSet.has(step)
  );
  const allCompleted = normalizeStringList([...existing.completed_steps, ...remaining]);
  const closedDoc: SessionCheckpointDocument = {
    ...existing,
    status: 'CERTIFIED_CLEAN',
    updated_at: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'),
    completed_steps: allCompleted,
    last_script_run: {
      cmd: ACTION_CLEAR,
      exit_code: 0,
      timestamp: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'),
      summary_1line: sanitizeSingleLineSec06(`[PASS] CLEAR${reasonSuffix}`),
    },
  };
  const projected = persistCheckpointAndProjection(ctx.checkpointPath, ctx.activeTaskPath, closedDoc);
  return {
    status: 'PASSED',
    action: ACTION_CLEAR,
    backend: BACKEND_NATIVE_TS,
    summary_1line: `[PASS] CLEAR | Task: ${closedDoc.task_id} | Estado: CERTIFIED_CLEAN`,
    checkpoint_path: ctx.checkpointPath,
    active_task_path: ctx.activeTaskPath,
    checkpoint: closedDoc,
    git_live: gitLive,
    active_task_markdown: projected,
  };
}

function buildErrorResult(
  action: string,
  checkpointPath: string,
  activeTaskPath: string,
  message: string
): FlightRecorderResult {
  return {
    status: 'FAILED',
    action,
    backend: BACKEND_NATIVE_TS,
    summary_1line: `[FAIL] CHECKPOINT | ${message}`,
    checkpoint_path: checkpointPath,
    active_task_path: activeTaskPath,
    checkpoint: null,
    error: message,
  };
}

interface PythonRecoverPayload {
  readonly has_checkpoint?: boolean;
  readonly checkpoint?: SessionCheckpointDocument;
  readonly live_git?: { readonly dirty_files?: readonly string[] };
}

function buildPythonRecoverResult(
  rawStdout: string,
  ctx: NativeActionContext,
  gitLive: FlightRecorderResult['git_live'],
  projected: string | undefined
): FlightRecorderResult {
  const parsed = JSON.parse(rawStdout) as PythonRecoverPayload;
  if (!parsed.checkpoint || parsed.has_checkpoint === false) {
    return {
      status: 'FAILED',
      action: ACTION_RECOVER,
      backend: BACKEND_PYTHON_CTL,
      summary_1line: `[FAIL] CHECKPOINT | Estado no inicializado en ${ctx.checkpointPath}`,
      checkpoint_path: ctx.checkpointPath,
      active_task_path: ctx.activeTaskPath,
      checkpoint: null,
      git_live: gitLive,
      error: 'No existe session_checkpoint.json ni ACTIVE_TASK.md previo para recuperar.',
    };
  }
  const dirtyCount = parsed.live_git?.dirty_files?.length ?? gitLive?.dirty_files_excluding_cache.length ?? 0;
  return {
    status: 'PASSED',
    action: ACTION_RECOVER,
    backend: BACKEND_PYTHON_CTL,
    summary_1line: `[PASS] RECOVER | Task: ${parsed.checkpoint.task_id} | Dirty: ${dirtyCount}`,
    checkpoint_path: ctx.checkpointPath,
    active_task_path: ctx.activeTaskPath,
    checkpoint: parsed.checkpoint,
    git_live: gitLive,
    active_task_markdown: projected,
  };
}

async function tryPythonCheckpointCtl(
  action: FlightRecorderAction,
  args: SessionFlightRecorderArgs,
  ctx: NativeActionContext,
  execFileFn: typeof execFile
): Promise<FlightRecorderResult | null> {
  const gitLive = collectLiveGitSnapshot(ctx.realRoot, ctx.execFileSyncFn);
  const priorClearDoc =
    action === ACTION_CLEAR
      ? readExistingCheckpoint(ctx.checkpointPath, ctx.activeTaskPath, gitLive)
      : null;
  const cliArgs = buildPythonCliArgs(ctx.realRoot, action, args);
  const res = await execFileAsync(execFileFn, 'python3', cliArgs, ctx.realRoot);
  if (res.errorCode === 'ENOENT') {
    return null;
  }
  if (res.exitCode !== 0) {
    const errMsg = sanitizeSingleLineSec06(res.stderr || res.stdout);
    return {
      status: 'FAILED',
      action,
      backend: BACKEND_PYTHON_CTL,
      summary_1line: `[FAIL] CHECKPOINT | ${errMsg}`,
      checkpoint_path: ctx.checkpointPath,
      active_task_path: ctx.activeTaskPath,
      checkpoint: null,
      error: errMsg,
    };
  }
  const projected = fs.existsSync(ctx.activeTaskPath)
    ? fs.readFileSync(ctx.activeTaskPath, UTF8_ENCODING)
    : undefined;
  if (action === ACTION_RECOVER) {
    return buildPythonRecoverResult(res.stdout, ctx, gitLive, projected);
  }
  const diskDoc = fs.existsSync(ctx.checkpointPath)
    ? (JSON.parse(fs.readFileSync(ctx.checkpointPath, UTF8_ENCODING)) as SessionCheckpointDocument)
    : null;
  const closedDoc =
    !diskDoc && action === ACTION_CLEAR && priorClearDoc
      ? { ...priorClearDoc, status: 'CERTIFIED_CLEAN' as const, planned_steps: [] }
      : diskDoc;
  return {
    status: 'PASSED',
    action,
    backend: BACKEND_PYTHON_CTL,
    summary_1line: sanitizeSingleLineSec06(res.stdout) || `[PASS] ${action.toUpperCase()}`,
    checkpoint_path: ctx.checkpointPath,
    active_task_path: ctx.activeTaskPath,
    checkpoint: closedDoc,
    git_live: gitLive,
    active_task_markdown: projected,
  };
}

const VALID_ACTIONS = new Set<FlightRecorderAction>([ACTION_SAVE, ACTION_RECOVER, ACTION_CLEAR]);

const NATIVE_ACTION_HANDLERS: Readonly<
  Record<
    FlightRecorderAction,
    (args: SessionFlightRecorderArgs, ctx: NativeActionContext) => FlightRecorderResult
  >
> = {
  [ACTION_SAVE]: executeNativeSave,
  [ACTION_RECOVER]: executeNativeRecover,
  [ACTION_CLEAR]: executeNativeClear,
};

function stringifyRawAction(rawAction: unknown): string {
  if (typeof rawAction === 'string') {
    return rawAction;
  }
  if (typeof rawAction === 'number' || typeof rawAction === 'boolean') {
    return String(rawAction);
  }
  return '';
}

function parseFlightRecorderAction(rawAction: unknown): FlightRecorderAction | null {
  const normalized = stringifyRawAction(rawAction).trim().toLowerCase() as FlightRecorderAction;
  return VALID_ACTIONS.has(normalized) ? normalized : null;
}

function resolveValidatedRecorderContext(
  rawArgs: SessionFlightRecorderArgs,
  deps: FlightRecorderDeps
): { readonly ok: true; readonly action: FlightRecorderAction; readonly ctx: NativeActionContext } | {
  readonly ok: false;
  readonly errorResult: FlightRecorderResult;
} {
  const action = parseFlightRecorderAction(rawArgs.action);
  if (!action) {
    const rawLabel = stringifyRawAction(rawArgs.action).trim().toLowerCase();
    return {
      ok: false,
      errorResult: buildErrorResult(
        rawLabel || 'unknown',
        '',
        '',
        `Acción inválida '${rawLabel}'. Valores permitidos: save, recover, clear.`
      ),
    };
  }
  const ws = resolveContainedWorkspace(rawArgs.project_path);
  if (!ws.ok) {
    return { ok: false, errorResult: buildErrorResult(action, '', '', ws.error) };
  }
  let checkpointPath: string;
  let activeTaskPath: string;
  try {
    checkpointPath = assertSafeTargetPath(ws.realRoot, CHECKPOINT_REL_PATH);
    activeTaskPath = assertSafeTargetPath(ws.realRoot, ACTIVE_TASK_REL_PATH);
  } catch (err) {
    return { ok: false, errorResult: buildErrorResult(action, '', '', (err as Error).message) };
  }
  const validationError = action === ACTION_SAVE ? validateSaveInputs(rawArgs) : null;
  if (validationError) {
    return {
      ok: false,
      errorResult: buildErrorResult(action, checkpointPath, activeTaskPath, validationError),
    };
  }
  return {
    ok: true,
    action,
    ctx: {
      realRoot: ws.realRoot,
      checkpointPath,
      activeTaskPath,
      execFileSyncFn: deps.execFileSyncFn ?? execFileSync,
    },
  };
}

export async function runSessionFlightRecorder(
  rawArgs: SessionFlightRecorderArgs = {},
  deps: FlightRecorderDeps = {}
): Promise<FlightRecorderResult> {
  const resolved = resolveValidatedRecorderContext(rawArgs, deps);
  if (!resolved.ok) {
    return resolved.errorResult;
  }
  const { action, ctx } = resolved;
  const execFileFn = deps.execFileFn ?? execFile;
  const hasCtlScript = fs.existsSync(path.join(ctx.realRoot, CHECKPOINT_CTL_REL_PATH));
  if (deps.preferPythonCtl !== false && hasCtlScript) {
    const pyResult = await tryPythonCheckpointCtl(action, rawArgs, ctx, execFileFn);
    if (pyResult !== null) {
      return pyResult;
    }
  }
  return NATIVE_ACTION_HANDLERS[action](rawArgs, ctx);
}

export async function handleSessionFlightRecorder(
  rawArgs: SessionFlightRecorderArgs = {},
  deps: FlightRecorderDeps = {}
): Promise<CallToolResult> {
  const result = await runSessionFlightRecorder(rawArgs, deps);
  return {
    isError: result.status === 'FAILED',
    content: [
      {
        type: 'text',
        text: JSON.stringify(result, null, 2),
      },
    ],
  };
}

export interface StageCmdCheckpointInput {
  readonly cmdName: string;
  readonly exitCode: number;
  readonly summary1Line: string;
}

/**
 * Registra de forma atómica el último resultado de etapa QA en session_checkpoint.json
 * y re-proyecta ACTIVE_TASK.md solo cuando existe una sesión activa (cero ruido fuera de sesión).
 */
export function recordStageCmdCheckpoint(
  projectPath: string,
  record: StageCmdCheckpointInput,
  execFileSyncFn: typeof execFileSync = execFileSync
): void {
  try {
    const ws = resolveContainedWorkspace(projectPath);
    if (!ws.ok) return;
    const checkpointPath = assertSafeTargetPath(ws.realRoot, CHECKPOINT_REL_PATH);
    const activeTaskPath = assertSafeTargetPath(ws.realRoot, ACTIVE_TASK_REL_PATH);
    if (!fs.existsSync(checkpointPath) && !fs.existsSync(activeTaskPath)) {
      return;
    }
    const gitLive = collectLiveGitSnapshot(ws.realRoot, execFileSyncFn);
    const current = readExistingCheckpoint(checkpointPath, activeTaskPath, gitLive);
    if (!current) return;
    const timestamp = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
    const nextDoc: SessionCheckpointDocument = {
      ...current,
      updated_at: timestamp,
      git_available: gitLive.git_available,
      branch: gitLive.branch,
      base_sha: gitLive.head_sha,
      last_script_run: {
        cmd: sanitizeSingleLineSec06(record.cmdName),
        exit_code: record.exitCode,
        timestamp,
        summary_1line: sanitizeSingleLineSec06(record.summary1Line),
      },
    };
    persistCheckpointAndProjection(checkpointPath, activeTaskPath, nextDoc);
  } catch (err: unknown) {
    // Non-blocking best-effort flight-recorder telemetry write on read-only/restricted filesystems
    reportDebugCatchError('sessionFlightRecorder.recordNativeScriptRun', err);
  }
}
