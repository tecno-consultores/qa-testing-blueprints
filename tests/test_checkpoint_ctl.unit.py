def test_lossless_autohydration_and_line_budget_compaction(
    tmp_path: Path, capsys: Any
) -> None:
    repo = _init_repo(tmp_path)
    agents_dir = repo / ".agents"
    agents_dir.mkdir(parents=True)
    # Plantilla identica a ACTIVE_TASK.md.example no hidrata
    (agents_dir / "ACTIVE_TASK.md.example").write_text("# tpl\n", encoding="utf-8")
    (agents_dir / "ACTIVE_TASK.md").write_text("# tpl\n", encoding="utf-8")
    assert ctl.main(["recover", "--workspace", str(repo), "--json"]) == 0
    empty_rec = json.loads(capsys.readouterr().out)
    assert empty_rec["has_checkpoint"] is False

    # Archivo legacy real con globs y pasos previos -> se auto-hidrata sin perdida
    legacy_md = (
        "# Registro\n"
        "**Tarea:** `LEGACY-9` | **Estado:** IN_PROGRESS\n"
        "**Objetivo:** Migrar modulo legacy\n"
        '- allowed_globs: ["api/**", "tests/**"]\n'
        "- forbidden_globs: infra/**\n"
        "- [x] Paso 1\n"
        "- [ ] Paso 2\n"
        "- [ ] Paso 3\n"
    )
    (agents_dir / "ACTIVE_TASK.md").write_text(legacy_md, encoding="utf-8")
    assert (
        ctl.main(
            [
                "set",
                "--workspace",
                str(repo),
                "--task-id",
                "HITO-9",
                "--step",
                "Paso 2",
                "--intent",
                "Continuando migracion",
            ]
        )
        == 0
    )
    capsys.readouterr()
    doc = json.loads(
        (agents_dir / ".cache" / "session_checkpoint.json").read_text(encoding="utf-8")
    )
    assert doc["completed_steps"] == ["Paso 1"]
    assert doc["allowed_globs"] == ["api/**", "tests/**"]
    assert doc["forbidden_globs"] == ["infra/**"]

    # Overflow > 50 pasos nunca supera 40 lineas
    many_done = ",".join(f"D{i}" for i in range(30))
    many_plan = ",".join(f"P{i}" for i in range(30))
    assert (
        ctl.main(
            [
                "set",
                "--workspace",
                str(repo),
                "--task-id",
                "HITO-BIG",
                "--step",
                "P0",
                "--done",
                many_done,
                "--planned",
                many_plan,
                "--intent",
                "Compactacion obligatoria",
            ]
        )
        == 0
    )
    capsys.readouterr()
    lines = (agents_dir / "ACTIVE_TASK.md").read_text(encoding="utf-8").splitlines()
    assert len(lines) <= 40
    assert len(lines) <= ctl.ACTIVE_TASK_MAX_LINES
    assert "pasos compactados" in "\n".join(lines)


def test_recover_git_crosscheck_noise_filter_and_clear(
    tmp_path: Path, capsys: Any
) -> None:
    repo = _init_repo(tmp_path)
    assert (
        ctl.main(
            [
                "set",
                "--workspace",
                str(repo),
                "--task-id",
                "HITO-RCV",
                "--step",
                "F1",
                "--intent",
                "Probar cruce git en vivo",
            ]
        )
        == 0
    )
    capsys.readouterr()

    # Ruido en .agents/.cache y ACTIVE_TASK.md se filtra; archivos reales se reportan
    cache_state = repo / ".agents" / ".cache" / "certify_state.json"
    cache_state.write_text("{}", encoding="utf-8")
    (repo / "README.md").write_text("# Edited\n", encoding="utf-8")
    (repo / "nuevo.py").write_text("x = 1\n", encoding="utf-8")

    # Avanzar HEAD y cambiar rama para detectar head_advanced + branch_mismatch
    _git(repo, "checkout", "-b", "feat/rama-nueva")
    _git(repo, "add", "README.md")
    _git(repo, "commit", "-m", "advance")
    # Renombrar para ejercitar _extract_porcelain_path con ' -> '
    _git(repo, "mv", "README.md", "README_NEW.md")

    assert ctl.main(["recover", "--workspace", str(repo), "--json"]) == 0
    rec = json.loads(capsys.readouterr().out)
    assert rec["has_checkpoint"] is True
    assert rec["branch_mismatch"] is True
    assert rec["head_advanced"] is True
    dirty = rec["live_git"]["dirty_files"]
    assert "nuevo.py" in dirty
    assert "README_NEW.md" in dirty
    assert all(".agents/.cache" not in f for f in dirty)
    assert all(".agents/ACTIVE_TASK.md" not in f for f in dirty)

    # Formato compacto texto
    assert ctl.main(["recover", "--workspace", str(repo)]) == 0
    txt_out = capsys.readouterr().out.strip()
    assert "[RECOVER] HITO-RCV" in txt_out
    assert "BRANCH_MISMATCH" in txt_out
    assert "HEAD_ADVANCED" in txt_out

    # Clear mantiene ACTIVE_TASK.md CERTIFIED_CLEAN y --purge-view lo elimina
    assert ctl.main(["clear", "--workspace", str(repo)]) == 0
    assert "[PASS] CHECKPOINT-CLEAR" in capsys.readouterr().out
    assert not (repo / ".agents" / ".cache" / "session_checkpoint.json").exists()
    active_after_clear = (repo / ".agents" / "ACTIVE_TASK.md").read_text(
        encoding="utf-8"
    )
    assert "**Estado:** CERTIFIED_CLEAN" in active_after_clear
    assert ctl.main(["clear", "--workspace", str(repo), "--purge-view"]) == 0
    capsys.readouterr()
    assert not (repo / ".agents" / "ACTIVE_TASK.md").exists()


def test_nogit_fallback_symlink_block_and_edge_cases(
    tmp_path: Path, capsys: Any, monkeypatch: pytest.MonkeyPatch
) -> None:
    plain_dir = tmp_path / "nogit_ws"
    plain_dir.mkdir()
    assert ctl.main(["recover", "--workspace", str(plain_dir)]) == 0
    assert "nogit@none" in capsys.readouterr().out

    assert (
        ctl.main(
            [
                "set",
                "--workspace",
                str(plain_dir),
                "--task-id",
                "NOGIT-1",
                "--step",
                "F1",
                "--intent",
                "Sin git local",
            ]
        )
        == 0
    )
    capsys.readouterr()
    doc = json.loads(
        (plain_dir / ".agents" / ".cache" / "session_checkpoint.json").read_text(
            encoding="utf-8"
        )
    )
    assert doc["git_available"] is False
    assert doc["branch"] == "nogit"
    assert doc["base_sha"] == "none"

    # Unborn git repo (sin commits)
    unborn = _init_repo(tmp_path / "u", with_commit=False)
    snap_unborn = ctl.capture_live_git(unborn)
    assert snap_unborn.git_available is True
    assert snap_unborn.head_sha == "unborn"
    assert snap_unborn.diff_stat_summary == "unborn HEAD"

    # Symlink escape bloqueado
    sym_ws = tmp_path / "sym_ws"
    (sym_ws / ".agents" / ".cache").mkdir(parents=True)
    outside = tmp_path / "outside.json"
    outside.write_text("{}", encoding="utf-8")
    (sym_ws / ".agents" / ".cache" / "session_checkpoint.json").symlink_to(outside)
    assert ctl.main(["recover", "--workspace", str(sym_ws)]) == 2
    assert "Symlink" in capsys.readouterr().err

    # JSON no-dict o corrupto
    bad_ws = tmp_path / "bad_json"
    (bad_ws / ".agents" / ".cache").mkdir(parents=True)
    (bad_ws / ".agents" / ".cache" / "session_checkpoint.json").write_text(
        "[]", encoding="utf-8"
    )
    assert ctl.main(["recover", "--workspace", str(bad_ws)]) == 2
    capsys.readouterr()

    # Timeout/OSError en git y branches helpers
    def raise_os(*_a: Any, **_kw: Any) -> Any:
        raise OSError("git missing")

    monkeypatch.setattr(subprocess, "run", raise_os)
    assert ctl._run_git(plain_dir, ["status"]) == (1, "")
    assert ctl._extract_porcelain_path("bad") == ""
    assert ctl._parse_glob_list("[invalid") == ("invalid",)
    assert ctl._try_parse_json_list('{"a": 1}') is None
    assert ctl._extract_task_id_from_lines(["sin tarea"]) == "LEGACY-TASK"
    assert ctl._extract_intent_from_lines(["sin objetivo"]) == "Tarea activa hidratada"
    (plain_dir / ".agents" / "ACTIVE_TASK.md").write_text("   \n", encoding="utf-8")
    assert ctl._is_non_template_active_task(plain_dir) is False
    # Limpieza de temporales y clear sin cache_dir/prev cubre ramas de handle_clear
    tmp_left = plain_dir / ".agents" / ".cache" / ".session_checkpoint.999.tmp"
    tmp_left.write_text("stale", encoding="utf-8")
    assert ctl.main(["clear", "--workspace", str(plain_dir)]) == 0
    capsys.readouterr()
    assert not tmp_left.exists()
    empty_ws = tmp_path / "empty_clear_ws"
    empty_ws.mkdir()
    assert ctl.main(["clear", "--workspace", str(empty_ws)]) == 0
    capsys.readouterr()
    # Cubrir hydrate desde ACTIVE_TASK legacy via recover sin .json
    legacy_ws = tmp_path / "legacy_hydrate"
    (legacy_ws / ".agents").mkdir(parents=True)
    (legacy_ws / ".agents" / "ACTIVE_TASK.md").write_text(
        "# Legacy\n- [x] DoneStep\n", encoding="utf-8"
    )
    assert ctl.main(["recover", "--workspace", str(legacy_ws)]) == 0
    assert "LEGACY-TASK" in capsys.readouterr().out
    # Cubrir _format_recover_compact sin flags de mismatch
    assert "[RECOVER] T" in ctl._format_recover_compact(
        {
            "has_checkpoint": True,
            "checkpoint": {
                "task_id": "T",
                "status": "IN_PROGRESS",
                "active_step": "F1",
                "completed_steps": [],
                "intent_140chars": "ok",
            },
            "live_git": {"dirty_files": []},
            "branch_mismatch": False,
            "head_advanced": False,
        }
    )


