def _git(repo: Path, *args: str) -> str:
    res = subprocess.run(
        ["git", *args],
        cwd=repo,
        capture_output=True,
        text=True,
        shell=False,
        check=True,
    )
    return res.stdout.strip()


def _init_repo(tmp_path: Path, *, with_commit: bool = True) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir(parents=True)
    _git(repo, "init", "-b", "main")
    _git(repo, "config", "user.email", "qa@tecno.local")
    _git(repo, "config", "user.name", "QA Bot")
    if with_commit:
        (repo / "README.md").write_text("# Init\n", encoding="utf-8")
        _git(repo, "add", "README.md")
        _git(repo, "commit", "-m", "init")
    return repo


def _assert_matches_schema(doc: dict[str, Any]) -> None:
    schema = json.loads(_SCHEMA_PATH.read_text(encoding="utf-8"))
    required = set(schema["required"])
    assert set(doc.keys()) == required
    assert doc["schema_version"] == "1.0"
    assert doc["status"] in ("IN_PROGRESS", "CERTIFIED_CLEAN")
    assert isinstance(doc["git_available"], bool)
    assert isinstance(doc["intent_140chars"], str)
    assert 1 <= len(doc["intent_140chars"]) <= 140


