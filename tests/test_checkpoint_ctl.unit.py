    assert "**Estado:** IN_PROGRESS" in md_text
    assert "- allowed_globs:" in md_text
    assert "- forbidden_globs:" in md_text
    assert "- [x] F1" in md_text
    assert "- [ ] F2" in md_text

    # Preserva allowed_globs/forbidden_globs/planned si no se pasan de nuevo
    rc2 = ctl.main(
        [
            "set",
            "--workspace",
            str(repo),
            "--task-id",
            "HITO-26",
            "--step",
            "F3",
            "--intent",
            "Paso 3 activo",
        ]
    )
    assert rc2 == 0
    capsys.readouterr()
    doc2 = json.loads(ckpt_file.read_text(encoding="utf-8"))
    assert doc2["completed_steps"] == ["F1"]
    assert doc2["allowed_globs"] == ["src/**", ".agents/**"]
